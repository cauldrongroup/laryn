import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dashboardDir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(dashboardDir, "..");
const distDir = path.join(appRoot, "dist");
const assetsDir = path.join(distDir, "assets");
const workerAssetsPath = path.resolve(appRoot, "..", "worker", "src", "dashboard-assets.ts");

async function firstExisting(paths) {
  for (const filePath of paths) {
    try {
      await readFile(filePath);
      return filePath;
    } catch {
      // Try the next Vite output shape.
    }
  }
  return null;
}

async function findAsset(extension) {
  const rootFiles = await readdir(distDir).catch(() => []);
  const assetFiles = await readdir(assetsDir).catch(() => []);
  const candidates = [
    ...rootFiles.map((file) => path.join(distDir, file)),
    ...assetFiles.map((file) => path.join(assetsDir, file))
  ];
  return candidates.find((file) => file.endsWith(extension)) ?? null;
}

const jsPath = await firstExisting([path.join(distDir, "dashboard.js")]) ?? await findAsset(".js");
const cssPath = await firstExisting([path.join(distDir, "dashboard.css")]) ?? await findAsset(".css");

if (!jsPath) {
  throw new Error("Could not find the built dashboard JavaScript asset.");
}

const js = await readFile(jsPath, "utf8");
const css = cssPath ? await readFile(cssPath, "utf8") : "";
const version = createHash("sha256").update(js).update(css).digest("hex").slice(0, 12);
const output = `// Generated by apps/dashboard/scripts/embed-worker-assets.mjs. Do not edit by hand.
export const DASHBOARD_CLIENT_JS = ${JSON.stringify(js)};
export const DASHBOARD_CLIENT_CSS = ${JSON.stringify(css)};
export const DASHBOARD_ASSET_VERSION = ${JSON.stringify(version)};
`;

await mkdir(path.dirname(workerAssetsPath), { recursive: true });
await writeFile(workerAssetsPath, output);
console.log(`Embedded dashboard assets in ${path.relative(process.cwd(), workerAssetsPath)}`);
